using Microsoft.Win32;
using System.Collections.Generic;
using System.IO.Ports;

namespace J2534
{
    /// <summary>
    /// Scans the Windows Registry for installed SAE J2534 PassThru devices.
    /// Checks both native and WOW6432Node registry paths for 32/64-bit compatibility.
    /// </summary>
    public static class J2534DeviceFinder
    {
        private const string PASSTHRU_REGISTRY_PATH = @"Software\PassThruSupport.04.04";
        private const string PASSTHRU_REGISTRY_PATH_6432 = @"Software\Wow6432Node\PassThruSupport.04.04";

        /// <summary>Find all installed J2534 PassThru DLLs from the Windows Registry</summary>
        public static List<J2534Device> FindInstalledJ2534DLLs()
        {
            var devices = new List<J2534Device>();
            var seenNames = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase);

            // Enumerate both registry paths and merge results (de-duplicate by Name)
            string[] registryPaths = { PASSTHRU_REGISTRY_PATH, PASSTHRU_REGISTRY_PATH_6432 };
            foreach (string regPath in registryPaths)
            {
                try
                {
                    using (RegistryKey baseKey = Registry.LocalMachine.OpenSubKey(regPath, false))
                    {
                        if (baseKey == null) continue;

                        foreach (string subKeyName in baseKey.GetSubKeyNames())
                        {
                          try
                          {
                            using (RegistryKey deviceKey = baseKey.OpenSubKey(subKeyName))
                            {
                                if (deviceKey == null) continue;

                                string name = (string)deviceKey.GetValue("Name", "");
                                if (seenNames.Contains(name)) continue;

                                var device = new J2534Device
                                {
                                    Vendor = (string)deviceKey.GetValue("Vendor", ""),
                                    Name = name,
                                    ConfigApplication = (string)deviceKey.GetValue("ConfigApplication", ""),
                                    FunctionLibrary = (string)deviceKey.GetValue("FunctionLibrary", ""),
                                    CAN = (int)deviceKey.GetValue("CAN", 0),
                                    ISO14230 = (int)deviceKey.GetValue("ISO14230", 0),
                                    ISO15765 = (int)deviceKey.GetValue("ISO15765", 0),
                                    ISO9141 = (int)deviceKey.GetValue("ISO9141", 0),
                                    J1850PWM = (int)deviceKey.GetValue("J1850PWM", 0),
                                    J1850VPW = (int)deviceKey.GetValue("J1850VPW", 0),
                                    SCI_A_ENGINE = (int)deviceKey.GetValue("SCI_A_ENGINE", 0),
                                    SCI_A_TRANS = (int)deviceKey.GetValue("SCI_A_TRANS", 0),
                                    SCI_B_ENGINE = (int)deviceKey.GetValue("SCI_B_ENGINE", 0),
                                    SCI_B_TRANS = (int)deviceKey.GetValue("SCI_B_TRANS", 0)
                                };
                                devices.Add(device);
                                seenNames.Add(name);
                            }
                          }
                          // Per-subkey guard — a single malformed registry entry (e.g. a
                          // non-int flag value) must not abort discovery of the rest.
                          catch (System.Exception ex) { System.Diagnostics.Debug.WriteLine($"J2534DeviceFinder: skipping malformed subkey '{subKeyName}': {ex.Message}"); }
                        }
                    }
                }
                catch (System.Exception ex) { System.Diagnostics.Debug.WriteLine($"J2534DeviceFinder registry error ({regPath}): {ex.Message}"); }
            }
            return devices;
        }

        /// <summary>
        /// Enumerate serial (COM) ports that could be an ELM327-class interface, labelled by
        /// what they actually are.
        /// </summary>
        /// <remarks>
        /// UNTIL 2026-08-04 THIS RETURNED EVERY COM PORT ON THE MACHINE AS AN "ELM327". A COM
        /// port carries no type information of its own, so that was the only thing it could
        /// do — but with a USB-serial CAN adapter attached, the adapter appeared twice in the
        /// device list: once mislabelled "ELM327 (COM10)" here, and once correctly in the
        /// Serial CAN block. Selecting the first sent an ELM327 AT handshake to a device that
        /// has never heard of AT commands.
        ///
        /// Ports are now classified by SerialPortClassifier, and anything identified as a
        /// USB-serial CAN adapter is EXCLUDED here — it belongs to the Serial CAN block. What
        /// remains is returned with an honest label: a confirmed ELM327 says so and carries
        /// its own version string, a Bluetooth RFCOMM port is labelled Bluetooth, and an
        /// unidentified port is offered as a plain serial port rather than claimed.
        /// </remarks>
        public static List<J2534Device> FindELM327Ports() => FindELM327Ports(probeUnknown: true);

        /// <param name="probeUnknown">
        /// When false, unidentified UART-bridge COM ports are NOT opened/sniffed — they are
        /// only classified from their PnP identity. The cold-startup populate passes false so
        /// the ~400ms-per-port SerialPort open does not sit on the pre-paint path; recognised
        /// ELM327 / Bluetooth / serial-CAN adapters still appear. The Scan button passes true.
        /// </param>
        public static List<J2534Device> FindELM327Ports(bool probeUnknown)
        {
            var devices = new List<J2534Device>();
            try
            {
                var ports = TesterPresent.OBD2.Transport.SerialCan.SerialPortClassifier
                                         .Enumerate(probeUnknown: probeUnknown);

                foreach (var p in ports)
                {
                    // Belongs to the Serial CAN block, not here. Listing it in both is what
                    // caused the duplicate-and-mislabelled entries this method used to produce.
                    if (p.Kind == TesterPresent.OBD2.Transport.SerialCan.SerialPortKind.SerialCan)
                        continue;

                    devices.Add(new J2534Device
                    {
                        Name = p.Label,
                        Vendor = p.Kind == TesterPresent.OBD2.Transport.SerialCan.SerialPortKind.Elm327
                                 ? "ELM327"
                                 : p.IsBluetooth ? "Bluetooth" : "Serial",
                        FunctionLibrary = "",      // No DLL — serial transport
                        ConfigApplication = "",
                        IsELM327 = true,           // routed through ELM327Transport when opened
                        ComPort = p.PortName,
                        // Capability flags stay optimistic: an ELM327 covers CAN, K-Line, VPW
                        // and PWM, and an unidentified port is not worth pre-emptively limiting.
                        CAN = 1,
                        ISO14230 = 1,
                        ISO15765 = 1,
                        ISO9141 = 1,
                        J1850PWM = 1,
                        J1850VPW = 1,
                        SCI_A_ENGINE = 0,
                        SCI_A_TRANS = 0,
                        SCI_B_ENGINE = 0,
                        SCI_B_TRANS = 0
                    });
                }
            }
            catch (System.Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"J2534DeviceFinder ELM327 COM port error: {ex.Message}");
            }
            return devices;
        }
    }
}

